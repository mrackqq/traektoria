/**
 * Правило годности анонимного идентификатора посетителя.
 *
 * Вынесено отдельным модулем намеренно: это правило нужно и middleware,
 * и серверным компонентам, а они живут в разных рантаймах. Middleware
 * работает на Edge, где нет `next/headers`, поэтому импортировать
 * `session-context` оттуда нельзя. Общим здесь остаётся только правило —
 * без cookie, без React, без Next.
 *
 * Одно правило на обе стороны важнее экономии файла: пока проверка на
 * выдаче (middleware) и проверка на чтении (session-context) расходились,
 * значение могло пройти первую и не пройти вторую — и посетитель оставался
 * без сессии, ничего об этом не узнав.
 */

/** Минимальная длина: короче — не идентификатор, а мусор или обрезок. */
const MIN_LENGTH = 8;
const MAX_LENGTH = 64;

/**
 * Пригодный идентификатор или `null`.
 *
 * Общего запасного значения нет намеренно. Раньше здесь возвращалась строка
 * `'guest'`, и все посетители без валидной cookie сходились на одного
 * владельца `user-guest`: читали и перезаписывали анкету и прогресс друг
 * друга. Отсутствие идентификатора — это отсутствие, а не ещё один общий
 * посетитель.
 */
export function sanitizeSessionId(raw: string | undefined): string | null {
  const cleaned = (raw ?? '').replace(/[^a-zA-Z0-9_-]/g, '').slice(0, MAX_LENGTH);
  return cleaned.length >= MIN_LENGTH ? cleaned : null;
}

/** Новый идентификатор посетителя. */
export function newSessionId(): string {
  return globalThis.crypto.randomUUID().replace(/-/g, '');
}
