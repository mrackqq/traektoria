/**
 * Граница того, что сервис действительно проверяет.
 *
 * Сервис знает один путь: гражданин Казахстана поступает после школы по
 * результатам ЕНТ. У выпускника колледжа порядок другой — сокращённые
 * образовательные программы, своя форма тестирования, диплом ТиПО вместо
 * аттестата и родственная специальность. У иностранного заявителя — своя
 * квота и свои вступительные испытания вместо ЕНТ.
 *
 * Эти правила мы не проверяли по источникам, поэтому не считаем и не
 * показываем. Молча выдать такому человеку школьный маршрут было бы хуже
 * отказа: он выглядит правдоподобно и уводит не туда.
 *
 * Модуль чистый: он только читает профиль.
 */

import type { ApplicantProfileRevision } from '../kernel/profile';
import { valueOf } from '../kernel/profile';

export interface ScopeLimit {
  readonly id: 'college' | 'foreign_applicant';
  readonly title: string;
  readonly message: string;
  /** Что человек может сделать прямо сейчас. */
  readonly whatWeCanDo: string;
}

const COLLEGE_LEVELS: readonly string[] = ['college_student', 'college_graduate'];

/**
 * Попадает ли профиль за границу проверяемого.
 *
 * Возвращается первое подходящее ограничение: показывать человеку два отказа
 * подряд незачем — достаточно назвать причину и честно сказать, что дальше.
 */
export function outOfScope(profile: ApplicantProfileRevision): ScopeLimit | null {
  const level = valueOf(profile.educationLevel);
  if (level !== undefined && COLLEGE_LEVELS.includes(level)) {
    return {
      id: 'college',
      title: 'Поступление после колледжа мы пока не проверяем',
      message:
        'У выпускников колледжа другой порядок: сокращённые образовательные программы, ' +
        'своя форма тестирования, диплом ТиПО вместо аттестата и требование родственной ' +
        'специальности. Мы не сверяли эти правила с официальными источниками, поэтому ' +
        'маршрут строить не будем — школьный план вам не подойдёт.',
      whatWeCanDo:
        'Ответы сохранены и никуда не денутся. Каталог программ, сроки приёмной кампании ' +
        'и стоимость обучения открыты — ими можно пользоваться, а условия допуска ' +
        'уточните в приёмной комиссии.',
    };
  }

  const citizenship = valueOf(profile.citizenship);
  const category = valueOf(profile.applicantCategory);
  if ((citizenship !== undefined && citizenship !== 'KZ') || category === 'foreign') {
    return {
      id: 'foreign_applicant',
      title: 'Приём иностранных заявителей мы пока не проверяем',
      message:
        'Иностранные заявители поступают не через ЕНТ: у них отдельная квота и свои ' +
        'вступительные испытания, а у части вузов — собственный порядок. Эти правила ' +
        'мы не сверяли с источниками и считать по ним не будем.',
      whatWeCanDo:
        'Ответы сохранены. Университеты со своим отбором — например, Nazarbayev ' +
        'University — проверяются как обычно: их условия не зависят от ЕНТ.',
    };
  }

  return null;
}
