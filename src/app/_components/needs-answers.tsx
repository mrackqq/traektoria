/**
 * Раздел, которому нечего показать до анкеты.
 *
 * Продукт построен на том, что не выдаёт неизвестное за известное. До
 * этого компонента он сам это правило и нарушал: человеку, не ответившему
 * ни на один вопрос, «Мои ответы» обещали «что мы поняли о вас», а
 * «Программы» показывали двадцать пять карточек под заголовком «какие
 * программы вам подходят» — все с пометкой «требует проверки» и
 * одинаковыми причинами, потому что проверять было нечего.
 *
 * Честный ответ на пустой профиль — сказать, что данных нет, объяснить,
 * что здесь появится, и дать один переход. Ровно это здесь и происходит.
 *
 * Пустое состояние намеренно называет ЦЕНУ анкеты. «Короткая анкета» без
 * числа — обещание, которое продукт не держит: вопросов там несколько
 * десятков. Обещание, которое нарушили на втором экране, стоит дороже,
 * чем отсутствие обещания.
 */

import Link from 'next/link';

import { Icon } from './icon';

export interface NeedsAnswersProps {
  /** Что этот раздел покажет, когда ответы появятся. */
  readonly gives: readonly string[];
  /** Чем этот раздел полезен — одной фразой, без обещаний. */
  readonly lede: string;
  /**
   * Охват каталога, если он отвечает на вопрос именно этого раздела.
   *
   * На «Программах» человек как раз и пришёл посмотреть, что есть. Отправить
   * его заполнять анкету, не сказав, из чего вообще будет подбор, — просить
   * работу авансом. На остальных разделах эта строка неуместна и не нужна.
   */
  readonly scope?: string;
}

export function NeedsAnswers({ gives, lede, scope }: NeedsAnswersProps) {
  return (
    <section className="needs-answers card stack-tight" aria-labelledby="needs-answers-heading">
      <p className="card__eyebrow">
        <Icon name="spark" size={16} /> Пока нечего показать
      </p>
      <h2 id="needs-answers-heading">Сначала расскажите о себе</h2>
      <p className="lede">{lede}</p>

      <div className="needs-answers__gives">
        <p className="card__eyebrow">Здесь появится</p>
        <ul className="stack-tight">
          {gives.map((item) => (
            <li key={item}>{item}</li>
          ))}
        </ul>
      </div>

      {scope ? (
        <p className="needs-answers__scope">
          <Icon name="programs" size={16} /> Сейчас в каталоге: {scope}.
        </p>
      ) : null}

      <div className="actions">
        <Link className="btn" href="/profile/edit">
          Заполнить анкету <Icon name="arrow" size={16} />
        </Link>
      </div>

      {/*
        Счёт шагов совпадает с тем, что человек увидит в самой анкете
        («шаг 1 из 6»): пять разделов с вопросами и шестой — проверка.
        Разойтись эти два числа не должны, иначе анкета с первого экрана
        выглядит длиннее обещанного.
      */}
      <p className="small muted">
        Пять разделов вопросов и проверка в конце. Отвечать подряд не нужно:
        ответы сохраняются на каждом шаге, а на любой вопрос можно ответить
        «не знаю» и вернуться позже — подбор учтёт то, что уже известно.
      </p>
    </section>
  );
}
