/**
 * Запрещённые утверждения в тексте модели.
 *
 * Здесь проверяется только лексическая часть: обещания зачисления, гарантии
 * и оценки вероятности. Привязка чисел к фактам лексикой не решается —
 * её проверяет `facts.test.ts`.
 *
 * Запуск: npm test
 */

import test from 'node:test';
import assert from 'node:assert/strict';

import { describeProblems, findForbiddenClaim } from './grounding.ts';

test('Вероятность числом словами отбрасывается', () => {
  const claim = findForbiddenClaim('Вероятность вашего зачисления составляет девяносто процентов.');
  assert.ok(claim, 'формулировка распознана как запрещённая');
});

test('Обещания зачисления в разных формулировках отбрасываются', () => {
  const promises = [
    'Мы гарантируем зачисление на эту программу.',
    'С такими баллами вы поступите без проблем.',
    'Вы точно пройдёте на грант.',
    'Ваши шансы на поступление высоки.',
    'Вероятность поступления составляет 85%.',
    'Это стопроцентный вариант.',
  ];

  for (const text of promises) {
    assert.ok(findForbiddenClaim(text), 'должно отбрасываться: ' + text);
  }
});

test('Нейтральное объяснение проходит лексическую проверку', () => {
  const text =
    'Программа совпадает с вашим направлением, но кампус находится за городом — ' +
    'закладывайте время на дорогу.';
  assert.equal(findForbiddenClaim(text), null);
});

test('Фактическое утверждение лексикой не отбрасывается: это задача проверки фактов', () => {
  // Само по себе предложение не содержит запрещённых слов. Его обязана
  // отбраковать проверка фактов, а не список формулировок.
  assert.equal(findForbiddenClaim('Подайте заявление до 12 октября 2030 года.'), null);
});

test('Пользователю объясняют, что именно убрано', () => {
  const messages = describeProblems([
    { code: 'PROBABILITY', detail: 'вероятность' },
    { code: 'GUARANTEE', detail: 'гарантия' },
  ]);

  assert.equal(messages.length, 2);
  assert.ok(messages.some((m) => /вероятност/i.test(m)));
  assert.ok(messages.some((m) => /гарантий/i.test(m)));
});
