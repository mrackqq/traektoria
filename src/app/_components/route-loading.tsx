/**
 * UX-08 — состояние загрузки маршрута.
 *
 * Пустой экран во время расчёта недопустим: пользователь должен понимать,
 * что происходит. Сообщение объявляется как live-region, чтобы экранный
 * диктор его прочитал (UX-09).
 *
 * Компонент вынесен из `app/loading.tsx` в общий модуль намеренно. Граница
 * загрузки в КОРНЕ приложения накрывает все маршруты сразу, а вместе с этим
 * ломает код ответа: Next начинает отдавать оболочку и фиксирует статус 200
 * раньше, чем страница успеет вызвать `notFound()`. Из-за этого
 * несуществующая программа отвечала «200 OK» со словами «Страница не
 * найдена» — для поисковиков и любого клиента это означает «страница есть».
 *
 * Поэтому граница теперь объявляется по сегментам: там, где она полезна, и
 * не там, где есть динамический параметр, который может не найтись.
 */

export function RouteLoading() {
  return (
    <div className="stack" role="status" aria-live="polite">
      <p className="card__eyebrow">Собираем всё вместе</p>
      <h1>Готовим ваш маршрут</h1>
      <p className="lede">
        Проверяем программы, условия и сроки по вашим данным. Это может занять немного времени.
      </p>
      <div className="loading-grid" aria-hidden="true"><div className="skeleton skeleton--wide" /><div className="skeleton" /><div className="skeleton" /></div>
    </div>
  );
}
